#!/usr/bin/env python3
"""Build a podium script for the short deck from its spoken notes.

Writes SPEAKING-SCRIPT-SHORT.md and SPEAKING-SCRIPT-SHORT.tex (compile to PDF).
The words are the frames' \\note scripts unchanged; this only adds layout and cues:
one sentence per line, [CLICK] where a build step appears, [ASK] and [PAUSE] beats.
"""
import re
from presenter_guide import ROOT, argument, command, plain

ACTS = {1: 'Motivation', 2: 'Examples', 3: 'Runtime: compute once', 4: 'Evidence: count once',
        5: 'Acceptance: publish once', 6: 'Open questions', 7: 'Conclusion'}
# Sentence prefixes, per frame file, before which the next build step appears.
CLICKS = {'04-waste': ['With reuse, we set up once'],
          '11-rules': ['Count once: what must', 'Publish once: who publishes'],
          '11b-rules-example': ['In one reported session, the agent made', 'After each five-minute run'],
          '19-runtime-cost': ['Take eight runs', 'With a warm cache, setup drops'],
          '25-evidence-precision': ['Our heuristic caps'],
          '26-acceptance-run': ['Review approved, suite green']}
# Sentence prefixes followed by a deliberate two-beat pause.
PAUSES = ['So the gain needs a separate held-out check', 'In a parallel, distributed world', 'Review approved, suite green', 'A person caught',
          'No test for the promise', 'The warm cache wins']
STRESS = ['Compute once', 'Count once', 'Publish once', 'Step one', 'Step two', 'Step three',
          'Rule one', 'Rule two', 'Rule three']

def sentences(text):
    return [s for s in re.split(r'(?<=[.?!])\s+(?=[A-Z0-9"])', text.strip()) if s]

def deck():
    src = (ROOT / 'talk-short.tex').read_text()
    act, clock = 0, 0
    for m in re.finditer(r'\\setact\{(\d+)\}|\\input\{short/([^}]+)\}', src):
        if m.group(1):
            act = int(m.group(1)); continue
        name = m.group(2); tex = (ROOT / 'short' / f'{name}.tex').read_text()
        frame = re.search(r'\\begin\{frame\}(?:\[[^]]*\])?(.*?)\\end\{frame\}', tex, re.S)
        if not frame: continue  # short/style.tex holds no frame
        body = frame.group(1).strip()
        title = plain(argument(body, 1))
        cue = re.match(r'\[(\d+):(\d{2})\]\s*(.*)', command(body, 'note'), re.S)
        dur = 60 * int(cue.group(1)) + int(cue.group(2))
        # Takeaway line without rule chips or overlay specs.
        claim = plain(re.sub(r'\\rulechip\{[^}]*\}|\\hfill|<\d+->', '', command(body, 'claim')))
        yield dict(name=name, act=act, title=title, dur=dur, start=clock, script=plain(cue.group(3)), claim=claim)
        clock += dur

def mmss(s): return f'{s // 60}:{s % 60:02d}'

def lines(slide):
    out, clicks = [], CLICKS.get(slide['name'], [])
    for s in sentences(slide['script']):
        marks = []
        if any(s.startswith(c) for c in clicks): marks.append('CLICK')
        if 'A question for you' in s: marks.append('ASK')
        pause = any(s.startswith(p) for p in PAUSES) or 'A question for you' in s
        out.append((marks, s, pause))
    return out

def stress_md(s):
    for w in STRESS: s = re.sub(rf'\b{w}\b', f'**{w}**', s)
    return s

def markdown(slides):
    total = sum(x['dur'] for x in slides)
    out = ['# Speaking script: Forkable Sandboxes (short deck)', '',
           f'Cambridge SRG, 15 October 2026. {len(slides)} slides, **{mmss(total)}** planned. '
           'The words are the slide notes; generated by `tools/speaking_script.py`.', '',
           '**Cues:** `[CLICK]` advance one build step · `[ASK]` question to the room · '
           '`[PAUSE]` two beats of silence · **bold** = stress.', '',
           '## Cue card', '', '| # | Starts | Land this |', '|---|---|---|']
    out += [f"| {i} | {mmss(x['start'])} | {x['claim'] or x['title']} |" for i, x in enumerate(slides, 1)]
    act = None
    for i, x in enumerate(slides, 1):
        if x['act'] != act:
            act = x['act']; end = max(y['start'] + y['dur'] for y in slides if y['act'] == act)
            out += ['', '---', '', f"## {act} · {ACTS[act]}  ({mmss(x['start'])}–{mmss(end)})"]
        out += ['', f"### {i:02d} · {x['title']}", '', f"*{mmss(x['dur'])} · starts {mmss(x['start'])}*", '']
        for marks, s, pause in lines(x):
            pre = ' '.join(f'`[{m}]`' for m in marks)
            out.append(f"> {pre + ' ' if pre else ''}{stress_md(s)}{' `[PAUSE]`' if pause else ''}  ")
    out += ['', '---', '', f'*End: {mmss(total)}. Leave the contributions slide up for questions.*', '']
    return '\n'.join(out)

TEX_ESC = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$', '#': r'\#', '_': r'\_',
           '{': r'\{', '}': r'\}', '~': r'\textasciitilde{}', '^': r'\textasciicircum{}',
           '→': r'$\rightarrow$', '×': r'$\times$', 'ρ': r'$\rho$', 'σ': r'$\sigma$', '±': r'$\pm$',
           '≤': r'$\leq$', '≥': r'$\geq$', '≠': r'$\neq$', '≈': r'$\approx$'}

def esc(s): return ''.join(TEX_ESC.get(c, c) for c in s)

def latex(slides):
    total = sum(x['dur'] for x in slides)
    tag = {'CLICK': r'\textcolor{Teal}{\textbf{[CLICK]}}', 'ASK': r'\textcolor{Gold}{\textbf{[ASK]}}'}
    out = [r'\documentclass[12pt]{article}', r'\usepackage[T1]{fontenc}', r'\usepackage[utf8]{inputenc}',
           r'\usepackage{lmodern}', r'\usepackage[margin=2cm]{geometry}', r'\usepackage{xcolor,longtable,booktabs,array}',
           r'\renewcommand{\familydefault}{\sfdefault}', r'\definecolor{Teal}{HTML}{007E87}',
           r'\definecolor{Gold}{HTML}{AD701B}', r'\definecolor{Muted}{HTML}{536874}', r'\definecolor{Ink}{HTML}{142B3B}',
           r'\setlength{\parindent}{0pt}', r'\pagestyle{plain}', r'\begin{document}', r'\color{Ink}',
           rf'{{\LARGE\bfseries Speaking script: Forkable Sandboxes}}\\[4pt]Cambridge SRG, 15 October 2026. '
           rf'{len(slides)} slides, \textbf{{{mmss(total)}}} planned.\\[4pt]'
           r'{\small Cues: \textcolor{Teal}{\textbf{[CLICK]}} advance one build step \quad '
           r'\textcolor{Gold}{\textbf{[ASK]}} question to the room \quad \textcolor{Muted}{[PAUSE]} two beats of silence \quad \textbf{bold} = stress}',
           r'\section*{Cue card}', r'{\small\begin{longtable}{@{}r r p{14cm}@{}}\toprule \# & Starts & Land this\\\midrule']
    out += [rf"{i} & {mmss(x['start'])} & {esc(x['claim'] or x['title'])}\\" for i, x in enumerate(slides, 1)]
    out += [r'\bottomrule\end{longtable}}', r'\newpage']
    act = None
    for i, x in enumerate(slides, 1):
        if x['act'] != act:
            act = x['act']; end = max(y['start'] + y['dur'] for y in slides if y['act'] == act)
            out.append(rf"\section*{{\textcolor{{Teal}}{{{act}\enspace {esc(ACTS[act])}}}\hfill{{\normalsize\color{{Muted}}{mmss(x['start'])}--{mmss(end)}}}}}")
        out += [r'\par\medskip\nopagebreak', rf"{{\large\bfseries {i:02d}\enspace {esc(x['title'])}}}\\*",
                rf"{{\small\color{{Muted}}{mmss(x['dur'])}, starts {mmss(x['start'])}}}\par\smallskip\nopagebreak"]
        for marks, s, pause in lines(x):
            t = esc(s)
            for w in STRESS: t = re.sub(rf'\b{w}\b', rf'\\textbf{{{w}}}', t)
            pre = ' '.join(tag[m] for m in marks)
            out.append(rf"\hangindent=1.2em {pre + ' ' if pre else ''}{t}{r' \textcolor{Muted}{[PAUSE]}' if pause else ''}\par")
    out += [r'\bigskip{\color{Muted}\itshape End: ' + mmss(total) + r'. Leave the contributions slide up for questions.}', r'\end{document}']
    return '\n'.join(out)

def main():
    slides = list(deck())
    (ROOT / 'SPEAKING-SCRIPT-SHORT.md').write_text(markdown(slides))
    (ROOT / 'SPEAKING-SCRIPT-SHORT.tex').write_text(latex(slides))
    missing = [(n, c) for n, cs in CLICKS.items() for c in cs
               if not any(s['name'] == n and c in s['script'] for s in slides)]
    if missing: raise SystemExit(f'Click cue not found in notes: {missing}')
    print(f'{len(slides)} slides; {mmss(sum(x["dur"] for x in slides))}; {sum(len(l) for l in CLICKS.values())} clicks')

if __name__ == '__main__': main()
